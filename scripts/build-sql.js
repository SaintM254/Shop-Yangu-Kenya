#!/usr/bin/env node
/* ============================================================ scripts/build-sql.js

   Writes the files you paste into Neon's SQL editor — for anyone who would
   rather not use a terminal at all.

   It takes the same files scripts/db-migrate.js runs and combines them in the
   right order, wrapped so that a person pasting them by hand gets the same
   two guarantees the script gives:

     1. ALL OR NOTHING. Everything runs in one transaction. If a line fails,
        nothing is applied and the database is exactly as it was.

     2. SAFE TO RUN TWICE. The first thing each file does is ask whether it
        has already been applied. If it has, it prints "Already applied" and
        stops. So a double-click on Run cannot break anything.

   It also writes the same progress table scripts/db-migrate.js uses, which
   means the two ways of setting up a database know about each other.

   Output:

     db/apply-all.sql          schema, functions and security — paste this first
     db/apply-demo.sql         a demo shop to look at — optional
     db/apply-super-admin.sql  makes one email address a platform admin

   Usage, from the repository root:

     node scripts/build-sql.js
     node scripts/build-sql.js --email you@example.com --name "Your Name"

   The email and name go into the super-admin file.
*/

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import crypto from 'node:crypto';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const db = path.join(root, 'db');

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf('--' + name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const email = flag('email', 'admin@shopyangu.co.ke');
const name = flag('name', 'Platform admin');

const read = (f) => fs.readFileSync(path.join(db, f), 'utf8');
const checksum = (f) => crypto.createHash('sha256').update(read(f)).digest('hex').slice(0, 16);
const quoted = (s) => s.replace(/'/g, "''");

/* Inside the DO block, a SELECT that returns rows has nowhere to go and
   Postgres refuses it. PERFORM is the plpgsql spelling of "run this and throw
   the answer away", which is exactly what these calls are. */
const asPerform = (sql) =>
  sql.replace(/^select (seed_demo|create_super_admin)\s*\(/gm, 'perform $1(');

/* --------------------------------------------------------------- the wrapper */

/* Postgres cannot skip statements halfway through a script, but it can run a
   whole migration conditionally inside one anonymous block. `$mig$` is a tag
   the inner SQL does not use (everything in db/ uses plain `$$`), so the two
   quote levels cannot be confused. */
function wrapped({ key, sum, title, notes, body }) {
  return `-- ============================================================================
--  Shop Yangu Kenya — ${title}
--
--  Generated by scripts/build-sql.js on ${new Date().toISOString().slice(0, 10)}.
--  Do not edit by hand: change the files in db/ and run that script again.
--
--  HOW TO USE THIS FILE
--
--    1. In Neon, open your project, then "SQL Editor" in the left sidebar.
--    2. Open this file in any plain text editor, select all, copy.
--    3. Paste it into the SQL editor and press Run.
--
--  You should see "Success" (or "APPLIED"). Running it a second time is safe:
--  it will say "Already applied — nothing to do" and skip the rest.
--
--  The whole file runs as one transaction. If any line fails, nothing at all
--  is applied and your database is left exactly as it was.
${notes ? '\n' + notes + '\n' : ''}-- ============================================================================

create table if not exists app_schema (
  file       text primary key,
  applied_at timestamptz not null default now(),
  checksum   text
);

begin;

do $mig$
begin
  if exists (select 1 from app_schema where file = '${key}' and checksum = '${sum}') then
    raise notice 'Already applied — nothing to do.';
    return;
  end if;

${body}

  delete from app_schema where file = '${key}';
  insert into app_schema (file, checksum, applied_at) values ('${key}', '${sum}', now());
  raise notice 'APPLIED.';
end
$mig$;

commit;
`;
}

/* ---------------------------------------------------------- 1. the database */

const all = wrapped({
  key: 'apply-all.sql',
  sum: checksum('001_schema.sql'),
  title: 'database setup',
  notes: `--  Creates the tables, the calculations and the access rules. After this,
--  the site has somewhere to keep shops, products, sales and customers, but
--  no shop yet. The next file adds one to look at.`,
  body: ['001_schema.sql', '002_functions.sql', '003_rls.sql']
    .map((f) => `-- ============================== db/${f} ==============================\n\n${read(f).trim()}`)
    .join('\n\n'),
});
fs.writeFileSync(path.join(db, 'apply-all.sql'), all);

/* ------------------------------------------------------------- 2. demo shop */

const demo = wrapped({
  key: 'apply-demo.sql',
  sum: checksum('004_seed_demo.sql'),
  title: 'demo shop (optional)',
  notes: `--  A working shop to look at while you set yours up: one branch in Mombasa,
--  twenty products, six customers and fourteen days of trading.
--
--  Skip this file if you are setting up a real shop. If you do run it and
--  later want it gone, run these three lines in the SQL editor, in this order:
--
--     alter table audit_entries disable trigger audit_entries_no_update;
--     delete from shops where name = 'Shop Yangu Kenya';
--     alter table audit_entries enable trigger audit_entries_no_update;`,
  body: asPerform(read('004_seed_demo.sql').trim()),
});
fs.writeFileSync(path.join(db, 'apply-demo.sql'), demo);

/* ----------------------------------------------------------- 3. super admin */

/* The function that creates an admin lives in 004_seed_demo.sql. Rather than
   make this file depend on the demo shop, the function is repeated here — it
   is idempotent and does nothing but insert one row. */
const seed = read('004_seed_demo.sql');
const fnStart = seed.indexOf('create or replace function create_super_admin');
if (fnStart < 0) {
  console.error('\n  Could not find create_super_admin() in db/004_seed_demo.sql.\n');
  process.exit(1);
}
const fnEnd = seed.indexOf('$$;', fnStart) + 3;
const adminFn = seed.slice(fnStart, fnEnd).trim();

const superAdmin = wrapped({
  key: 'apply-super-admin.sql',
  sum: checksum('004_seed_demo.sql'),
  title: 'platform admin',
  notes: `--  Makes ${email} a platform admin.
--
--  A platform admin can sign in at /admin/ and see every shop on the platform,
--  and pause one. They cannot read any shop's sales, products or customers —
--  that stays with the shop's own owner.`,
  body: `${asPerform(adminFn)}

  perform create_super_admin('${quoted(email)}', '${quoted(name)}');`,
});
fs.writeFileSync(path.join(db, 'apply-super-admin.sql'), superAdmin);

/* ------------------------------------------------------------------ report */

const size = (f) => Math.round(fs.statSync(path.join(db, f)).size / 1024) + ' kB';

console.log('');
console.log('  Three files written to db/:');
console.log('');
console.log(`    apply-all.sql           ${size('apply-all.sql').padStart(7)}   ← paste this first`);
console.log(`    apply-demo.sql          ${size('apply-demo.sql').padStart(7)}   ← optional, a shop to look at`);
console.log(`    apply-super-admin.sql   ${size('apply-super-admin.sql').padStart(7)}   ← the admin: ${email}`);
console.log('');
console.log('  Open one in a plain text editor, copy all of it, and paste it into');
console.log('  the SQL editor in Neon. Each says "APPLIED" when it works and is safe');
console.log('  to run twice.');
console.log('');
