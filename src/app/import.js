function csvOf(rows) {
  return rows.map(r => r.map(c => /[",\n]/.test(String(c)) ? '"' + String(c).replace(/"/g, '""') + '"' : String(c)).join(',')).join('\r\n');
}
/* Save a file from the browser. `data` is a string for CSV and a byte array
   for the workbook, so one function covers both; `announce` controls the
   toast, because a template download is already obvious. */
function downloadFile(name, data, type, announce) {
  try {
    const blob = data instanceof Blob ? data : new Blob([data], { type: type || 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 4000);
    if (announce) toast('Downloaded ' + name, 'good');
  } catch (err) {
    toast('This browser blocked the download. Open the site in a normal tab and try again.', 'bad');
  }
}

/* ---- reading a CSV ---- */
/* note: no top-level name may shadow a built-in used elsewhere — `sum` is the app's own */
function parseCSV(text) {
  const rows = [];
  let row = [], cell = '', q = false;
  text = text.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += ch;
  }
  if (cell.length || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.some(c => String(c).trim() !== ''));
}

/* ---- date handling, the part that matters ---- */
function readDate(s, allowFuture) {
  const v = String(s || '').trim();
  if (!v) return { ok: true, date: null };
  if (/^\d{4}-\d{2}-\d{2}$/.test(v)) {
    const d = new Date(v + 'T00:00:00');
    if (isNaN(d)) return { ok: false, why: 'not a real date' };
    const back = ymd(d);
    if (back !== v) return { ok: false, why: 'not a real date' };
    return finishDate(d, allowFuture);
  }
  /* DD/MM/YY, the format the app prints everywhere — never MM/DD. A
     two-digit year is read as 20yy: a shop importing its history is not
     entering 1919. DD/MM/YYYY is accepted too, because Excel writes it. */
  if (/^\d{1,2}\/\d{1,2}\/\d{2,4}$/.test(v)) {
    const [dd, mm, yRaw] = v.split('/').map(Number);
    const yy = yRaw < 100 ? 2000 + yRaw : yRaw;
    const d = new Date(yy, mm - 1, dd);
    if (d.getDate() !== dd || d.getMonth() !== mm - 1 || d.getFullYear() !== yy) {
      return { ok: false, why: 'not a real date' };
    }
    return finishDate(d, allowFuture);
  }
  if (/^\d{5}$/.test(v)) {
    /* an Excel serial date, what a raw export often holds */
    const d = new Date(Date.UTC(1899, 11, 30) + Number(v) * 86400000);
    if (isNaN(d)) return { ok: false, why: 'not a real date' };
    return finishDate(d, allowFuture);
  }
  if (/^\d{4}-\d{2}-\d{2}T/.test(v)) {
    const d = new Date(v);
    if (!isNaN(d)) return finishDate(new Date(d.getFullYear(), d.getMonth(), d.getDate()), allowFuture);
  }
  return { ok: false, why: 'use DD/MM/YY' };
}
function finishDate(d, allowFuture) {
  if (!allowFuture && d > today()) return { ok: false, why: 'in the future', date: d };
  return { ok: true, date: d };
}

function validate(kind, rows) {
  const sc = SCHEMAS[kind];
  const head = rows[0].map(h => String(h).trim().toLowerCase());
  const missing = sc.cols.filter(c => !head.includes(c));
  const extra = head.filter(h => h && !sc.cols.includes(h));
  const seenSku = new Map(), seenReceipt = new Map();
  const good = [], bad = [];
  let lastGroup = '';
  for (let r = 1; r < rows.length; r++) {
    const raw = rows[r];
    /* The template ships with a filled example row. It is a shape to copy,
       not a sale, so it is skipped by its marker rather than imported. */
    if (/^\(?example/i.test(String(raw[0] == null ? '' : raw[0]).trim())) continue;
    if (!raw.some(v => String(v == null ? '' : v).trim() !== '')) continue;
    const o = {};
    sc.cols.forEach(c => { o[c] = String(raw[head.indexOf(c)] == null ? '' : raw[head.indexOf(c)]).trim(); });
    const errs = [];

    if (kind === 'products') {
      if (!o.name) errs.push('no name');
      /* A blank SKU is not an error: the shop should not have to invent
         codes. One is generated from the category, and checked against the
         sheet and against the price list so it cannot collide. */
      if (!o.sku) {
        o.sku = nextSku(o.category);
        let n = 0;
        while (seenSku.has(o.sku) || S.products.some(p => p.sku === o.sku)) {
          n++;
          o.sku = o.sku.replace(/-\d+$/, '') + '-' + String(Number(o.sku.split('-').pop()) + 1).padStart(3, '0');
          if (n > 999) break;
        }
        o._generated = 'sku';
      } else if (seenSku.has(o.sku)) errs.push('sku repeats row ' + seenSku.get(o.sku));
      else seenSku.set(o.sku, r + 1);
      if (o.selling_price && isNaN(Number(o.selling_price))) errs.push('selling_price is not a number');
      if (o.cost_price && isNaN(Number(o.cost_price))) errs.push('cost_price is not a number');
      if (o.opening_qty && (!/^\d+$/.test(o.opening_qty))) errs.push('opening_qty must be a whole number');
      /* an expiry date is normally in the future; only a sale cannot be */
      const d = readDate(o.expiry_date, true);
      if (!d.ok) errs.push('expiry_date ' + d.why);
      o._date = d.date;
    }
    if (kind === 'customers') {
      if (!o.name) errs.push('no name');
      if (o.opening_balance && isNaN(Number(o.opening_balance))) errs.push('opening_balance is not a number');
      const d = readDate(o.since);
      if (!d.ok) errs.push('since ' + d.why);
      o._date = d.date;
    }
    if (kind === 'sales') {
      /* A blank receipt number is generated. Rows with the same number are
         one receipt, so the first blank row opens an invoice and the ones
         after it join that invoice rather than each being numbered. */
      if (!o.receipt_no) {
        o.receipt_no = o._lastGroup || nextReceiptNo();
      } else if (seenReceipt.has(o.receipt_no)) {
        errs.push('receipt already imported');
      } else {
        seenReceipt.set(o.receipt_no, r + 1);
      }
      if (/^\*/.test(o.customer || '')) o.customer = ''; /* a note row, not a sale */
      if (!o.sku) errs.push('no sku');
      if (!/^\d+(\.\d+)?$/.test(o.qty || '')) errs.push('qty must be a number');
      if (!/^\d+(\.\d+)?$/.test(o.unit_price || '')) errs.push('unit_price must be a number');
      const d = readDate(o.date);
      if (!d.ok) errs.push('date ' + d.why + ' (' + o.date + ')');
      o._date = d.date;
      if (o.amount_paid && isNaN(Number(o.amount_paid))) errs.push('amount_paid is not a number');
    }
    if (errs.length) bad.push({ row: r + 1, errs, o });
    else {
      good.push(o);
      if (kind === 'sales' && o.receipt_no) lastGroup = o.receipt_no;
    }
  }
  return { head, missing, extra, good, bad, total: rows.length - 1 };
}

function handleFile(file) {
  const reader = new FileReader();
  reader.onload = () => {
    const rows = parseCSV(String(reader.result));
    if (!rows.length) { toast('That file is empty.', 'bad'); return; }
    parsed = { kind: importTarget, rows };
    renderImportReport(validate(importTarget, rows), rows);
  };
  reader.onerror = () => toast('Could not read that file.', 'bad');
  reader.readAsText(file);
}

