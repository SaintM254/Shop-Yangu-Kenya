/* ============================================================ import from Excel / CSV

   The template and the importer are the same document, generated from the
   same schema: the columns a shop is asked to fill are the columns the
   reader looks for. A template that drifts from its reader is worse than no
   template at all, so both come from SCHEMAS and nothing else.

   Two rules shape the columns:
     · dates are DD/MM/YY, as they are written on every screen and report
     · codes the shop should not have to invent — a product's SKU, a
       receipt's number — are generated by the app, so the column is `auto`
       and is filled in on import when the sheet leaves it blank */
const SCHEMAS = {
  products: {
    label: 'Products / stock',
    hint: 'One row per product. The SKU is filled in for you if you leave it blank.',
    cols: ['sku', 'name', 'category', 'unit', 'cost_price', 'selling_price', 'opening_qty', 'reorder_level', 'expiry_date', 'supplier', 'barcode'],
    auto: ['sku'],
    sample: ['', 'Sugar 2kg', 'Grocery', 'packet', '205', '240', '68', '24', '', 'Kwa Nguvu Distributors', '6001234500012'],
    dateCols: ['expiry_date']
  },
  customers: {
    label: 'Customers',
    hint: 'One row per customer. Leave the phone blank for a cash customer.',
    cols: ['name', 'phone', 'credit_limit', 'opening_balance', 'since', 'notes'],
    auto: [],
    sample: ['Mama Zawadi Kiosk', '0722118044', '20000', '8650', '11/03/24', 'Kiosk on Moi Avenue'],
    dateCols: ['since']
  },
  sales: {
    label: 'Sales history',
    hint: 'One row per item sold. Rows with the same receipt_no are one receipt.',
    cols: ['receipt_no', 'date', 'customer', 'sku', 'qty', 'unit_price', 'amount_paid', 'payment_method', 'cashier', 'notes'],
    auto: ['receipt_no'],
    sample: ['', '01/04/26', 'Hotel Bahari', 'DRK-001', '24', '50', '1200', 'M-Pesa', 'Otieno Were', 'March order, settled'],
    dateCols: ['date']
  }
};

/* A code with a readable prefix and no collisions: GRC-001, R-2101. Called
   only when the shop left the cell empty — a code they typed is theirs. */
function nextSku(cat) {
  const prefix = ({ Grocery: 'GRC', Drinks: 'DRK', Household: 'HHD', 'Personal care': 'PRC', Hardware: 'HDW' })[cat] || 'SKU';
  const used = new Set(S.products.map(p => String(p.sku || '').toUpperCase()));
  let n = 1;
  while (used.has(prefix + '-' + String(n).padStart(3, '0'))) n++;
  return prefix + '-' + String(n).padStart(3, '0');
}
function nextReceiptNo() {
  const used = new Set(S.sales.map(s => String(s.no || '')));
  let n = 2101;
  while (used.has('R-' + n)) n++;
  return 'R-' + n;
}

