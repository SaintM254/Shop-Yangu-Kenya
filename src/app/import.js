/* The template, as a workbook: a title and a line of instructions, the
   header row, then one filled example row — the same example the sheet
   describes — so the shape is obvious without reading anything. The example
   row is marked in its own column, so a shop can see it, and the importer
   skips any row whose first cell starts with "Example". */
function templateGuide(kind) {
  const sc = SCHEMAS[kind];
  const sample = sc.cols.map((c, i) => (c === 'sku' || c === 'receipt_no') ? '(filled in for you)' : sc.sample[i] || '');
  return {
    name: 'How to fill it',
    title: sc.label + ' — what goes in each column',
    subtitle: sc.cols.length + ' columns. Delete the example row before adding your own.',
    note: 'Import it back as CSV: File > Save as > CSV UTF-8.',
    columns: [
      { label: 'Column', width: 20 },
      { label: 'What goes in it', width: 52 },
      { label: 'Example', width: 28 },
    ],
    rows: sc.cols.map((c, i) => [c, kindHint(kind, c), sample[i] || '']),
  };
}

